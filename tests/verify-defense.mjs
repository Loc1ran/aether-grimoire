import assert from 'node:assert/strict';
import { cli } from './iwsdk.mjs';
const sleep=ms=>new Promise(resolve=>setTimeout(resolve,ms));
const index=cli('ecs','find',{withComponents:['Combat']}).result.entities[0].entityIndex;
const state=()=>cli('ecs','query',{entityIndex:index}).result.components.find(c=>c.componentId==='Combat').values;
cli('xr','set-input-mode',{mode:'controller'});
cli('xr','set-connected',{device:'controller-left',connected:true});cli('xr','set-connected',{device:'controller-right',connected:true});
cli('xr','set-gamepad-state',{device:'controller-left',buttons:[{index:3,value:0}]});
const targets=cli('xr','list-targets',{}).result.targets;
const button=targets.find(t=>t.name==='emitter-button');
const before=state().casts;
cli('xr','look-at',{device:'controller-right',target:button.position});
cli('xr','select',{device:'controller-right',duration:.25});
assert.equal(state().casts,before,'UI clicks cannot cast');
const panel=cli('ecs','find',{namePattern:'Training Guide'}).result.entities[0].entityIndex;
assert.equal(cli('ui','inspect',{entityIndex:panel,selector:'#emitter-button'}).result.elements[0].text,'Pause trial');
cli('xr','look-at',{device:'controller-right',target:{x:2,y:1,z:-3}});
cli('xr','set-transform',{device:'controller-left',position:{x:0,y:1.38,z:-.6}});
cli('xr','look-at',{device:'controller-left',target:{x:0,y:1.7,z:-3.3}});
cli('xr','set-gamepad-state',{device:'controller-left',buttons:[{index:3,value:1}]});
await sleep(6500);
console.log('DEFENSE',JSON.stringify(state()));assert.ok(state().blocks>=1,'shield blocks live incoming projectile');
await sleep(6500);
console.log('BREAK',JSON.stringify(state()));assert.ok(state().blocks>=3,'shield takes three hits');assert.equal(state().spellLeft,'','broken shield remains down while held');
cli('browser','screenshot',{},['--output-file','artifacts/defense-runtime.png']);
cli('xr','set-gamepad-state',{device:'controller-left',buttons:[{index:3,value:0}]});
cli('xr','look-at',{device:'controller-right',target:button.position});cli('xr','select',{device:'controller-right',duration:.2});
cli('xr','look-at',{device:'controller-right',target:{x:2,y:1,z:-3}});
console.log('PASS UI guard, trial control, shield block/break/release');

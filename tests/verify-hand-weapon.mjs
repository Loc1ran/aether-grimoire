import assert from 'node:assert/strict';
import { Vector3, Quaternion } from '@iwsdk/core';
import { cli } from './iwsdk.mjs';
const sleep=ms=>new Promise(resolve=>setTimeout(resolve,ms));
const index=cli('ecs','find',{withComponents:['Combat']}).result.entities[0].entityIndex;
const query=()=>cli('ecs','query',{entityIndex:index}).result;
const state=()=>query().components.find(c=>c.componentId==='Combat').values;
const transform=query().components.find(c=>c.componentId==='Transform').values;
const normal=new Vector3(0,0,1).applyQuaternion(new Quaternion().fromArray(transform.orientation));
const portal=new Vector3().fromArray(transform.position).addScaledVector(normal,.045);
const handle=portal.clone().addScaledVector(normal,.29);
const position=v=>({x:v.x,y:v.y,z:v.z});
cli('xr','set-input-mode',{mode:'hand'});
cli('xr','set-transform',{device:'hand-left',anchor:'wrist',position:{x:-.35,y:1,z:-.2},orientation:{fingers:'forward',palm:'down'}});
cli('xr','set-hand-pose',{device:'hand-left',poseId:'fist'});
cli('xr','set-select-value',{device:'hand-right',value:0});
cli('xr','set-hand-pose',{device:'hand-right',poseId:'open'});
cli('xr','set-transform',{device:'hand-right',anchor:'grip',position:position(portal),orientation:{fingers:'up',palm:'forward'}});
cli('xr','set-hand-pose',{device:'hand-right',poseId:'fist'});
await sleep(500);console.log('FIST',JSON.stringify(state()));assert.equal(state().weapon,'Ready');
cli('xr','set-hand-pose',{device:'hand-right',poseId:'open'});
cli('xr','set-transform',{device:'hand-right',anchor:'grip',position:position(handle)});
cli('xr','set-hand-pose',{device:'hand-right',poseId:'fist'});
assert.equal(state().weapon,'Extracting');
cli('xr','animate-to',{device:'hand-right',anchor:'grip',position:position(handle.clone().addScaledVector(normal,.65)),duration:1});
console.log('HAND SWORD',JSON.stringify(state()));assert.equal(state().weapon,'Held');
cli('xr','set-connected',{device:'hand-right',connected:false});await sleep(800);
assert.equal(state().weapon,'Stored','tracking loss returns sword');
cli('xr','set-connected',{device:'hand-right',connected:true});
cli('xr','set-select-value',{device:'hand-right',value:0});
cli('xr','set-transform',{device:'hand-right',anchor:'wrist',position:{x:.1,y:1.28,z:-.2},orientation:{fingers:'up',palm:'forward'}});
cli('xr','set-hand-pose',{device:'hand-right',poseId:'open'});await sleep(1800);
const casts=state().casts;
cli('xr','animate-to',{device:'hand-right',anchor:'wrist',position:{x:.1,y:1.28,z:-.62},duration:.3});
console.log('PALM BLAST',JSON.stringify(state()));assert.ok(state().casts>casts);
cli('xr','set-hand-pose',{device:'hand-right',poseId:'default'});
console.log('PASS hand-only sword prepare/extract, tracking loss, charged palm push');

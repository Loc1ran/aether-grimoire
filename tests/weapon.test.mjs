import { build } from 'esbuild';
const contents = `
import assert from 'node:assert/strict';
import { Group, Mesh, Vector3 } from '@iwsdk/core';
import { createSword } from './src/scene-assets/combat.scene-asset.ts';
import { WeaponController } from './src/weapon-controller.ts';
import { createHandIntent } from './src/magic-input.ts';
const sword = createSword(), book = new Group(), portal = new Mesh();
const events = [];
const w = new WeaponController(sword, book, {portal}, (event) => events.push(event));
const hand = createHandIntent('right'); hand.tracked = true; hand.validConfidence = 1;
const hands = [hand];
w.update(.02, hands, true);
assert.equal(w.state, 'Stored');
hand.grab = hand.grabDown = true; w.update(.02, hands, true); hand.grabDown = false;
for(let i=0;i<20;i++) w.update(.02, hands, true);
assert.equal(w.state, 'Ready');
hand.position.copy(w.handlePosition); hand.grabDown = true; w.update(.02, hands, true);
assert.equal(w.state, 'Ready', 'holding the first grab cannot start extraction');
hand.grab = hand.grabDown = false; w.update(.02, hands, true);
hand.grab = hand.grabDown = true; w.update(.02, hands, true); hand.grabDown = false;
assert.equal(w.state, 'Extracting');
hand.position.addScaledVector(w.portalNormal, .3); w.update(.02, hands, true);
assert.ok(w.progress > .54 && w.progress < .56);
const extended = w.progress;
hand.position.addScaledVector(w.portalNormal, -.1); w.update(.02, hands, true);
assert.ok(w.progress < extended, 'backward pull retracts blade');
hand.position.addScaledVector(w.portalNormal, .36); w.update(.02, hands, true);
assert.equal(w.state, 'Held'); assert.equal(w.swingSpeed, 0, 'completion cannot produce phantom damage');
assert.equal(sword.scale.x, 1);
hand.tracked = false;
for(let i=0;i<8;i++) w.update(.02, hands, true);
assert.equal(w.state, 'Returning');
for(let i=0;i<30;i++) w.update(.02, hands, true);
assert.equal(w.state, 'Stored'); assert.equal(w.holderIndex, -1); assert.equal(sword.visible, false);
assert.deepEqual(events.slice(0,3), ['prepare','grab','extract']);
w.dispose(); console.log('PASS weapon intent, regrab, signed pull, rigid reveal, ownership, tracking-loss return');
`;
const result = await build({stdin:{contents, resolveDir:process.cwd(), loader:'ts'},bundle:true,write:false,format:'esm',platform:'node',packages:'external'});
const code = result.outputFiles[0].text.replaceAll('"@iwsdk/core"', JSON.stringify(import.meta.resolve('@iwsdk/core')));
await import('data:text/javascript;base64,'+Buffer.from(code).toString('base64'));

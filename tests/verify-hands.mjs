import assert from 'node:assert/strict';
import { cli } from './iwsdk.mjs';
const sleep=ms=>new Promise(resolve=>setTimeout(resolve,ms));
cli('browser','reload',{});
await sleep(1500);
const book=cli('ecs','find',{withComponents:['Combat']}).result.entities[0].entityIndex;
const state=()=>cli('ecs','query',{entityIndex:book}).result.components.find(c=>c.componentId==='Combat').values;
if(!cli('xr','status').result.sessionActive)cli('xr','enter',{});
cli('xr','set-input-mode',{mode:'hand'});
cli('xr','set-connected',{device:'hand-right',connected:true});
cli('xr','set-connected',{device:'hand-left',connected:true});
cli('xr','set-select-value',{device:'hand-right',value:0});
cli('xr','set-transform',{device:'hand-left',anchor:'wrist',position:{x:-.3,y:1,z:-.2},orientation:{fingers:'forward',palm:'down'}});
cli('xr','set-hand-pose',{device:'hand-left',poseId:'default'});
cli('xr','set-transform',{device:'hand-right',anchor:'wrist',position:{x:.2,y:1.15,z:-.3},orientation:{fingers:'up',palm:'forward'}});
cli('xr','set-hand-pose',{device:'hand-right',poseId:'open'});
await sleep(250);
console.log('OPEN',JSON.stringify(state()));
assert.equal(state().state,'Dormant','open palm cannot summon');
cli('xr','set-select-value',{device:'hand-right',value:1,duration:.15});await sleep(350);
console.log('PINCH',JSON.stringify(cli('xr','get-hand-state',{device:'hand-right'}).result));
cli('xr','animate-to',{device:'hand-right',anchor:'wrist',position:{x:.2,y:1.35,z:-.3},duration:.6});
cli('xr','set-select-value',{device:'hand-right',value:0,duration:.15});await sleep(1400);
console.log('SUMMON',JSON.stringify(state()));assert.equal(state().state,'Idle','pinch and pull summons');
cli('xr','set-transform',{device:'hand-right',anchor:'wrist',position:{x:.2,y:1.3,z:-.45},orientation:{fingers:'forward',palm:'left'}});
cli('xr','set-hand-pose',{device:'hand-right',poseId:'point'});await sleep(250);
console.log('POINT',JSON.stringify(state()));
cli('xr','look-at',{device:'hand-right',target:{x:0,y:1.2,z:-2.5}});
cli('xr','set-select-value',{device:'hand-right',value:1,duration:.12});await sleep(400);
cli('xr','set-select-value',{device:'hand-right',value:0,duration:.12});await sleep(700);
console.log('BOLT',JSON.stringify(state()));assert.ok(state().casts>=1,'point-pinch-release casts');
cli('xr','set-hand-pose',{device:'hand-right',poseId:'peace'});await sleep(500);
console.log('TWO',JSON.stringify(state()));
cli('xr','animate-to',{device:'hand-right',anchor:'wrist',position:{x:.65,y:1.3,z:-.45},duration:.3});await sleep(400);
console.log('SLASH',JSON.stringify(state()));assert.ok(state().casts>=2,'two finger sweep casts');
cli('xr','set-hand-pose',{device:'hand-right',poseId:'default'});
cli('xr','set-transform',{device:'hand-left',anchor:'wrist',position:{x:-.05,y:1.2,z:-.6},orientation:{fingers:'up',palm:'forward'}});
cli('xr','set-hand-pose',{device:'hand-left',poseId:'open'});await sleep(550);
console.log('SHIELD',JSON.stringify(state()));assert.equal(state().spellLeft,'shield','extended open palm shields');
cli('browser','screenshot',{},['--output-file','artifacts/hand-shield-runtime.png']);
cli('xr','set-hand-pose',{device:'hand-left',poseId:'default'});
console.log('PASS native joint hand summon, bolt, slash, shield');

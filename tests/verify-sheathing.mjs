import assert from 'node:assert/strict';
import { Vector3, Quaternion } from '@iwsdk/core';
import { cli } from './iwsdk.mjs';
const sleep=ms=>new Promise(resolve=>setTimeout(resolve,ms));
const index=cli('ecs','find',{withComponents:['Combat']}).result.entities[0].entityIndex;
const query=()=>cli('ecs','query',{entityIndex:index}).result;
const state=()=>query().components.find(c=>c.componentId==='Combat').values;
const position=v=>({x:v.x,y:v.y,z:v.z});
assert.equal(state().state,'Idle','open the book before testing insertion');
if(state().weapon==='Stored') {
  const portal=new Vector3().fromArray(query().components.find(c=>c.componentId==='Transform').values.position);portal.y+=.045;
  const handle=portal.clone();handle.y+=.29;
  cli('xr','set-gamepad-state',{device:'controller-right',buttons:[{index:0,value:0},{index:1,value:0}]});
  cli('xr','set-transform',{device:'controller-right',position:position(portal),orientation:{pitch:0,yaw:0,roll:0}});
  cli('xr','set-gamepad-state',{device:'controller-right',buttons:[{index:1,value:1}]});
  await sleep(600);assert.equal(state().weapon,'Ready');
  cli('xr','set-gamepad-state',{device:'controller-right',buttons:[{index:1,value:0}]});
  cli('xr','set-transform',{device:'controller-right',position:position(handle)});
  cli('xr','set-gamepad-state',{device:'controller-right',buttons:[{index:1,value:1}]});
  assert.equal(state().weapon,'Extracting');
  handle.y+=.62;
  cli('xr','animate-to',{device:'controller-right',position:position(handle),duration:.9});
  assert.equal(state().weapon,'Held');
}
cli('xr','set-gamepad-state',{device:'controller-right',buttons:[{index:1,value:0}]});
await sleep(700);assert.equal(state().weapon,'Held','releasing grip must keep sword equipped');
cli('xr','set-connected',{device:'controller-right',connected:false});await sleep(300);
assert.equal(state().weapon,'Held','tracking loss must not store sword');
cli('xr','set-connected',{device:'controller-right',connected:true});
cli('xr','set-transform',{device:'controller-right',position:{x:.25,y:1.2,z:-.3}});await sleep(500);
const opening=new Vector3().fromArray(query().components.find(c=>c.componentId==='Transform').values.position);opening.y+=.045;
cli('xr','set-transform',{device:'controller-right',position:position(opening),orientation:{pitch:0,yaw:0,roll:0}});
assert.equal(state().weapon,'Held','handle proximity must not store sword');
const swordIndex=cli('ecs','find',{namePattern:'^Veilblade$'}).result.entities[0].entityIndex;
const actual=cli('ecs','query',{entityIndex:swordIndex}).result.components.find(c=>c.componentId==='Transform').values;
const device=cli('xr','get-device-state',{}).result.controllers.right;
const deviceRotation=new Quaternion(device.orientation.x,device.orientation.y,device.orientation.z,device.orientation.w);
const gripOffset=deviceRotation.clone().invert().multiply(new Quaternion().fromArray(actual.orientation));
const positionOffset=new Vector3().fromArray(actual.position).sub(new Vector3(device.position.x,device.position.y,device.position.z)).applyQuaternion(deviceRotation.clone().invert());
const downRotation=new Quaternion().setFromAxisAngle(new Vector3(1,0,0),Math.PI).multiply(gripOffset.invert());
const controllerPosition=v=>position(v.clone().sub(positionOffset.clone().applyQuaternion(downRotation)));
const orientation={x:downRotation.x,y:downRotation.y,z:downRotation.z,w:downRotation.w};
const above=opening.clone();above.y+=.96;
cli('xr','set-transform',{device:'controller-right',position:controllerPosition(above),orientation});
await sleep(200);
const entered=opening.clone();entered.y+=.8;
cli('xr','animate-to',{device:'controller-right',position:controllerPosition(entered),duration:.7});
assert.equal(state().weapon,'Sheathing','downward tip entry must start insertion');
const halfway=opening.clone();halfway.y+=.5;
cli('xr','animate-to',{device:'controller-right',position:controllerPosition(halfway),duration:.8});
assert.ok(state().extraction>.35&&state().extraction<.65,'partial insertion must track depth');
await sleep(500);assert.equal(state().weapon,'Sheathing','waiting cannot finish insertion');
cli('browser','screenshot',{},['--output-file','artifacts/katana-insertion.png']);
const seated=opening.clone();seated.y+=.12;
cli('xr','animate-to',{device:'controller-right',position:controllerPosition(seated),duration:1});
assert.equal(state().weapon,'Stored');
console.log('PASS persistent equip, tracking pause, top-entry, partial insertion, and manual full sheathing');

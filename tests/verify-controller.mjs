import assert from 'node:assert/strict';
import { cli } from './iwsdk.mjs';
const sleep = ms => new Promise(resolve=>setTimeout(resolve,ms));
const entity=cli('ecs','find',{withComponents:['Combat']}).result.entities[0].entityIndex;
const query=()=>cli('ecs','query',{entityIndex:entity}).result;
const state=()=>query().components.find(c=>c.componentId==='Combat').values;
const xr=cli('xr','status').result;
if(!xr.sessionActive)cli('xr','enter',{});
cli('xr','set-input-mode',{mode:'controller'});
cli('xr','set-connected',{device:'controller-right',connected:true});
cli('xr','set-connected',{device:'controller-left',connected:true});
cli('xr','set-transform',{device:'controller-right',position:{x:0.25,y:1.25,z:-0.4}});
cli('xr','set-gamepad-state',{device:'controller-right',buttons:[{index:0,value:1},{index:1,value:1}]});
await sleep(850);
cli('xr','set-gamepad-state',{device:'controller-right',buttons:[{index:0,value:0},{index:1,value:0}]});
await sleep(1500);
console.log('SUMMON',JSON.stringify(state()));
assert.equal(state().state,'Idle');
cli('xr','look-at',{device:'controller-right',target:{x:0,y:1.2,z:-2.5}});
cli('xr','set-select-value',{device:'controller-right',value:1});
await sleep(450);
cli('xr','set-select-value',{device:'controller-right',value:0});
await sleep(700);
let current=state(); console.log('BOLT',JSON.stringify(current));
assert.ok(current.casts>=1,'bolt released');assert.ok(current.hits>=1,'bolt hit target');
cli('xr','set-gamepad-state',{device:'controller-right',buttons:[{index:4,value:1}]});
await sleep(1800);
cli('xr','set-gamepad-state',{device:'controller-right',buttons:[{index:4,value:0}]});
await sleep(850);
current=state();console.log('BLAST',JSON.stringify(current));assert.ok(current.casts>=2,'charged blast released');
cli('xr','set-gamepad-state',{device:'controller-right',buttons:[{index:2,value:1}]});
await sleep(500);
cli('xr','set-gamepad-state',{device:'controller-right',buttons:[{index:2,value:0}]});
await sleep(700);
current=state();console.log('SLASH',JSON.stringify(current));assert.ok(current.casts>=3,'slash released');
console.log('PASS controller summon, bolt, charged blast, slash, target hits');
